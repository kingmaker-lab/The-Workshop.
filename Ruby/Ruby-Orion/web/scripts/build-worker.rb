#!/usr/bin/env ruby
# frozen_string_literal: true
# Reproducible deployment bundle for the separate Ruby Orion Studio Worker.
require "json"
require "fileutils"

root = File.expand_path("..", __dir__)
mapping = {
  "/" => ["index.html", "text/html; charset=utf-8"],
  "/index.html" => ["index.html", "text/html; charset=utf-8"],
  "/assets/studio.css" => ["assets/studio.css", "text/css; charset=utf-8"],
  "/assets/favicon.svg" => ["assets/favicon.svg", "image/svg+xml"],
  "/assets/studio.js" => ["assets/studio.js", "application/javascript; charset=utf-8"],
  "/assets/bench.js" => ["assets/bench.js", "application/javascript; charset=utf-8"],
  "/assets/ruby-worker.js" => ["assets/ruby-worker.js", "application/javascript; charset=utf-8"],
  "/data/labs.json" => ["data/labs.json", "application/json; charset=utf-8"]
}

assets = mapping.transform_values do |relative, content_type|
  file = File.expand_path(relative, root)
  abort "Invalid asset path: #{relative}" unless file.start_with?(root + File::SEPARATOR)
  abort "Missing asset: #{file}" unless File.file?(file)
  { type: content_type, body: File.read(file, encoding: "UTF-8") }
end

csp = "default-src 'none'; script-src 'self' https://cdn.jsdelivr.net 'wasm-unsafe-eval'; " \
      "worker-src 'self' https://cdn.jsdelivr.net; connect-src 'self' https://cdn.jsdelivr.net; style-src 'self'; " \
      "img-src 'self' data:; font-src 'self'; base-uri 'none'; form-action 'none'; " \
      "frame-ancestors 'none'; object-src 'none'"

source = <<~JS
  // Generated by web/scripts/build-worker.rb. Do not edit this output.
  const ASSETS = #{JSON.generate(assets)};
  const CSP = #{JSON.generate(csp)};
  export default {
    async fetch(request) {
      const url = new URL(request.url);
      const headers = new Headers({
        "Content-Security-Policy": CSP,
        "X-Content-Type-Options": "nosniff",
        "X-Frame-Options": "DENY",
        "Referrer-Policy": "no-referrer",
        "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=()",
        "Cross-Origin-Resource-Policy": "same-origin"
      });
      if (!["GET", "HEAD"].includes(request.method)) {
        headers.set("Allow", "GET, HEAD");
        return new Response("Method Not Allowed", {status: 405, headers});
      }
      const asset = Object.prototype.hasOwnProperty.call(ASSETS, url.pathname) ? ASSETS[url.pathname] : null;
      if (!asset) {
        headers.set("Content-Type", "text/plain; charset=utf-8");
        headers.set("Cache-Control", "no-store");
        return new Response("Not Found", {status: 404, headers});
      }
      headers.set("Content-Type", asset.type);
      headers.set("Cache-Control", url.pathname === "/" || url.pathname === "/index.html"
        ? "public,max-age=300" : "public,max-age=600");
      return new Response(request.method === "HEAD" ? null : asset.body, {status: 200, headers});
    }
  };
JS

directory = File.join(root, "dist")
FileUtils.mkdir_p(directory)
File.write(File.join(directory, "worker.mjs"), source)
puts "Orion Studio Worker: #{assets.length} routes, #{source.bytesize} bytes, CSP enabled."
