#!/usr/bin/env ruby
# frozen_string_literal: true
# Reproducible, dependency-free packaging of the public Ruby Hub into a Worker.
require "json"
require "fileutils"

ROOT = File.expand_path("..", __dir__)
ASSET_PATHS = {
  "/" => ["index.html", "text/html; charset=utf-8"],
  "/index.html" => ["index.html", "text/html; charset=utf-8"],
  "/assets/styles.css" => ["assets/styles.css", "text/css; charset=utf-8"],
  "/assets/app.js" => ["assets/app.js", "application/javascript; charset=utf-8"],
  "/assets/favicon.svg" => ["assets/favicon.svg", "image/svg+xml"],
  "/data/projects.json" => ["data/projects.json", "application/json; charset=utf-8"]
}.freeze

assets = ASSET_PATHS.transform_values do |relative, mime|
  path = File.expand_path(relative, ROOT)
  abort "Unsafe path" unless path.start_with?("#{ROOT}/")
  abort "Missing asset: #{relative}" unless File.file?(path)
  { type: mime, body: File.read(path, encoding: "UTF-8") }
end

script = <<~JS
  // Generated by scripts/build_worker.rb; do not edit generated output.
  const ASSETS = #{JSON.generate(assets)};
  const CSP = "default-src 'none'; script-src 'self'; style-src 'self'; img-src 'self' data:; connect-src 'self'; font-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'; object-src 'none'";
  export default {
    async fetch(request) {
      const url = new URL(request.url);
      const headers = new Headers({
        "Content-Security-Policy": CSP,
        "X-Content-Type-Options": "nosniff",
        "Referrer-Policy": "strict-origin-when-cross-origin",
        "X-Frame-Options": "DENY",
        "Permissions-Policy": "camera=(), microphone=(), geolocation=()"
      });
      if (request.method !== "GET" && request.method !== "HEAD") {
        headers.set("Allow", "GET, HEAD");
        return new Response("Method Not Allowed", {status: 405, headers});
      }
      const file = Object.prototype.hasOwnProperty.call(ASSETS, url.pathname) ? ASSETS[url.pathname] : null;
      if (!file) {
        headers.set("Content-Type", "text/plain; charset=utf-8");
        return new Response("Not Found", {status: 404, headers});
      }
      headers.set("Content-Type", file.type);
      headers.set("Cache-Control", url.pathname === "/" || url.pathname === "/index.html" ? "public,max-age=300" : "public,max-age=600");
      return new Response(request.method === "HEAD" ? null : file.body, {status: 200, headers});
    }
  };
JS

directory = File.join(ROOT, "dist")
FileUtils.mkdir_p(directory)
File.write(File.join(directory, "worker.js"), script)
puts "Ruby Hub Worker generated: #{script.bytesize} bytes, #{assets.size} routes"
